/**
 * Mencari POI Sukabumi berdasarkan kata kunci
 */
export function searchSukabumiPOI(query: string): SukabumiPOI[] {
  const clean = query.trim().toLowerCase()
  if (!clean) return []

  const tokens = clean.split(/\s+/).filter(Boolean)

  return SUKABUMI_POIS.filter((poi) => {
    const haystack = `${poi.name} ${poi.address} ${poi.keywords.join(' ')}`.toLowerCase()
    return tokens.every((token) => haystack.includes(token))
  })
}
