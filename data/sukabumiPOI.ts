/**
 * Memperluas token pencarian dengan sinonim & singkatan umum di Sukabumi
 */
function expandTokens(tokens: string[]): string[][] {
  return tokens.map((token) => {
    const variants = new Set<string>([token])

    // SMA / SMAN / SMU / SLTA
    if (token === 'sma' || token === 'sman' || token === 'smu' || token === 'slta') {
      variants.add('sma')
      variants.add('sman')
    }
    // SMK / SMKN / STM / SMEA / KEJURUAN
    else if (token === 'smk' || token === 'smkn' || token === 'stm' || token === 'smea') {
      variants.add('smk')
      variants.add('smkn')
      variants.add('stm')
      variants.add('smea')
    }
    // SMP / SMPN / SLTP
    else if (token === 'smp' || token === 'smpn' || token === 'sltp') {
      variants.add('smp')
      variants.add('smpn')
    }
    // SD / SDN
    else if (token === 'sd' || token === 'sdn') {
      variants.add('sd')
      variants.add('sdn')
    }
    // MAN / Madrasah Aliyah
    else if (token === 'man' || token === 'aliyah') {
      variants.add('man')
      variants.add('aliyah')
      variants.add('madrasah')
    }
    // MTs / Tsanawiyah
    else if (token === 'mts' || token === 'mtsn' || token === 'tsanawiyah') {
      variants.add('mts')
      variants.add('mtsn')
      variants.add('tsanawiyah')
    }
    // Universitas / Perguruan Tinggi / Kampus / Kuliah
    else if (token === 'univ' || token === 'universitas' || token === 'kampus' || token === 'kuliah' || token === 'pt') {
      variants.add('universitas')
      variants.add('univ')
      variants.add('kampus')
      variants.add('kuliah')
      variants.add('stie')
      variants.add('stikes')
      variants.add('politeknik')
      variants.add('stai')
      variants.add('stisip')
    }
    // Pesantren / Ponpes
    else if (token === 'ponpes' || token === 'pesantren' || token === 'pondok') {
      variants.add('ponpes')
      variants.add('pesantren')
      variants.add('pondok')
    }
    // Rumah Sakit / RS / RSUD
    else if (token === 'rs' || token === 'rsud' || token === 'rumahsakit') {
      variants.add('rs')
      variants.add('rsud')
      variants.add('rumah sakit')
    }
    // Jalan / Gang / Kampung / Desa / Kecamatan
    else if (token === 'jl' || token === 'jln' || token === 'jalan') {
      variants.add('jalan')
      variants.add('jl')
    } else if (token === 'gg' || token === 'gang') {
      variants.add('gang')
      variants.add('gg')
    } else if (token === 'kp' || token === 'kampung') {
      variants.add('kampung')
      variants.add('kp')
    } else if (token === 'ds' || token === 'desa') {
      variants.add('desa')
      variants.add('ds')
    } else if (token === 'kec' || token === 'kecamatan') {
      variants.add('kecamatan')
      variants.add('kec')
    } else if (token === 'kel' || token === 'kelurahan') {
      variants.add('kelurahan')
      variants.add('kel')
    }

    return Array.from(variants)
  })
}

/**
 * Mencari POI Sukabumi berdasarkan kata kunci dengan alias cerdas dan penilaian relevansi
 */
export function searchSukabumiPOI(query: string): SukabumiPOI[] {
  const clean = query.trim().toLowerCase()
  if (!clean) return []

  const rawTokens = clean.split(/\s+/).filter(Boolean)
  const tokenGroups = expandTokens(rawTokens)

  const matches = SUKABUMI_POIS.map((poi) => {
    const nameLower = poi.name.toLowerCase()
    const addressLower = poi.address.toLowerCase()
    const keywordsLower = poi.keywords.map((k) => k.toLowerCase()).join(' ')
    const fullHaystack = `${nameLower} ${addressLower} ${keywordsLower}`

    // Setiap token pencarian harus memiliki variasi yang cocok di haystack
    const isMatch = tokenGroups.every((variants) =>
      variants.some((v) => fullHaystack.includes(v))
    )

    if (!isMatch) return null

    // Hitung bobot relevansi (prioritaskan kecocokan pada NAMA tempat)
    let score = 0
    if (nameLower.startsWith(clean)) score += 500
    else if (nameLower.includes(clean)) score += 300

    // Tambah bobot untuk setiap kata/token yang ada di dalam nama tempat
    const tokensInName = rawTokens.filter((t) => nameLower.includes(t)).length
    score += tokensInName * 80

    if (poi.keywords.some((k) => k.toLowerCase() === clean)) score += 150
    else if (poi.keywords.some((k) => k.toLowerCase().includes(clean))) score += 70

    // Kecocokan di alamat diberi bobot kecil agar tidak mendistraksi nama tempat
    if (addressLower.includes(clean)) score += 20

    return { poi, score }
  })
    .filter((item): item is { poi: SukabumiPOI; score: number } => item !== null)
    .sort((a, b) => b.score - a.score)
    .map((item) => item.poi)

  return matches
}

